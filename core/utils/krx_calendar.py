def is_krx_trading_day(d: Optional[date] = None) -> bool:
    """주어진 날짜(기본값: 오늘 KST)가 한국거래소 정상 거래일인지 판별."""
    if d is None:
        d = datetime.now(tz=KST).date()

    # 1. 주말(토, 일) 제외
    if d.weekday() >= 5:
        return False

    # 2. 증시 휴장일 목록 확인
    date_str = d.strftime("%Y-%m-%d")
    if date_str in KRX_HOLIDAYS:
        return False

    # 3. 고정 공휴일 기본 규칙 (목록 누락 시의 방어선)
    # 신정(1/1), 삼일절(3/1), 근로자의 날(5/1), 어린이날(5/5), 현충일(6/6),
    # 광복절(8/15), 개천절(10/3), 한글날(10/9), 성탄절(12/25), 연말 폐장일(12/31)
    if (d.month, d.day) in [
        (1, 1), (3, 1), (5, 1), (5, 5), (6, 6),
        (8, 15), (10, 3), (10, 9), (12, 25), (12, 31)
    ]:
        return False

    return True


def is_krx_market_open_now(dt: Optional[datetime] = None) -> bool:
    """현재 시각(KST)이 KRX 정규장 개장 중(09:00 ~ 15:30, 공휴일 제외)인지 확인."""
    if dt is None:
        dt = datetime.now(tz=KST)
    else:
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=KST)
        else:
            dt = dt.astimezone(KST)

    # 거래일인지 확인
    if not is_krx_trading_day(dt.date()):
        return False

    # 정규장 매매시간: 09:00:00 ~ 15:30:00
    open_time = dt.replace(hour=9, minute=0, second=0, microsecond=0)
    close_time = dt.replace(hour=15, minute=30, second=0, microsecond=0)
    return open_time <= dt <= close_time

