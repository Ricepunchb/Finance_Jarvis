"""한국거래소(KRX) 개장일 및 휴장일(공휴일, 근로자의 날, 연말 폐장일 등) 판별 모듈.

한국거래소 증권시장 업무규정에 따른 휴장일:
1. 토요일, 일요일
2. 관공서의 공휴일에 관한 규정에 따른 공휴일 (대체공휴일 포함)
3. 근로자의 날 (5월 1일)
4. 연말 최종 매매일 다음 날 (통상 12월 31일, 31일이 주말이면 직전 평일)
"""
from datetime import date, datetime
from typing import Optional, Set
from zoneinfo import ZoneInfo

KST = ZoneInfo("Asia/Seoul")

# 2024 ~ 2028년 한국거래소 확정/예정 증시 휴장일 (YYYY-MM-DD 형식, 주말 제외 평일 휴장일 목록)
